const { withAppBuildGradle } = require('expo/config-plugins');

const marker = '// @generated by with-android-apk-splits';

/**
 * Keep both supported CPU architectures without putting both sets of native
 * libraries into one oversized universal APK. Gradle emits one APK per ABI.
 */
module.exports = (config) => withAppBuildGradle(config, (modConfig) => {
  if (modConfig.modResults.language !== 'groovy') {
    throw new Error('with-android-apk-splits only supports Groovy build.gradle files');
  }

  if (!modConfig.modResults.contents.includes(marker)) {
    modConfig.modResults.contents = modConfig.modResults.contents.replace(
      /android\s*\{/,
      `android {
    ${marker}
    splits {
        abi {
            reset()
            enable true
            universalApk false
            include "armeabi-v7a", "arm64-v8a"
        }
    }`,
    );
  }

  return modConfig;
});
